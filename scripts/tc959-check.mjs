import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isDeepStrictEqual } from 'node:util';
import { buildConfig, nodeImage, ingressImage, vectorImage } from './tc959-logship.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const args = process.argv.slice(2);
if (args.length && (args.length !== 2 || args[0] !== '--canonical')) throw new Error('usage: tc959-check.mjs [--canonical PATH_TO_CANONICAL_FIELDS]');
const bytes = readFileSync(resolve(root, 'log-shipper/fields.json'));
const pin = JSON.parse(readFileSync(resolve(root, 'log-shipper/canonical.json'), 'utf8'));
assert.match(pin.revision, /^[0-9a-f]{40}$/);
assert.equal(createHash('sha256').update(bytes).digest('hex'), pin.sha256, 'vendored schema differs from reviewed canonical hash');
if (args[1]) assert.deepEqual(bytes, readFileSync(args[1]), 'canonical/vendor schema bytes differ');
const result = spawnSync('docker', ['compose', '--env-file', '/dev/null', '-f', resolve(root, 'docker-compose.dstack-postgres.yaml'), 'config', '--no-interpolate', '--no-env-resolution', '--format', 'json'], { encoding: 'utf8', maxBuffer: 4 * 1024 * 1024 });
assert.equal(result.status, 0, 'compose structure cannot be parsed without env interpolation');
const compose = JSON.parse(result.stdout);
const services = compose.services;
assert.equal(services.tinycloud.image, nodeImage, 'N0 must use unchanged production node digest');
assert.equal(services['dstack-ingress'].image, ingressImage, 'N0 must use unchanged ingress digest');
assert.equal(services.tinycloud.environment.TINYCLOUD_LOG__FORMAT, 'Json');
assert.deepEqual(Object.keys(services.tinycloud.networks), ['default']);
assert.deepEqual(Object.keys(services['dstack-ingress'].networks), ['default']);
for (const [name, label] of [['tinycloud', 'tinycloud-node'], ['dstack-ingress', 'tinycloud-ingress']]) {
  const service = services[name];
  assert.equal(service.labels['tc.logship'], label);
  assert.equal(service.logging.driver, 'gelf');
  assert.equal(service.logging.options['gelf-address'], 'udp://127.0.0.1:12201');
  assert.equal(service.logging.options.labels, 'tc.logship');
  assert.equal(service.logging.options.mode, 'non-blocking');
  assert.equal(service.logging.options['cache-disabled'], 'true');
}
const vector = services.vector;
assert.equal(vector.image, vectorImage);
assert.equal(vector.user, '10001:10001');
assert.equal(vector.read_only, true);
assert.deepEqual(vector.cap_drop, ['ALL']);
assert.ok(vector.security_opt.includes('no-new-privileges:true'));
assert.ok(['64m', '67108864'].includes(String(vector.mem_limit)));
assert.ok(['64m', '67108864'].includes(String(vector.memswap_limit)));
assert.equal(Number(vector.cpus), 0.5);
assert.equal(vector.privileged ?? false, false);
assert.equal(vector.network_mode, undefined);
assert.deepEqual(Object.keys(vector.networks), ['logship']);
assert.equal(vector.volumes, undefined, 'Vector must not mount Docker, dstack, app data, or host files');
assert.equal(vector.ports.length, 1);
assert.equal(vector.ports[0].host_ip, '127.0.0.1');
assert.equal(vector.ports[0].target, 12201);
assert.equal(vector.ports[0].published, '12201');
assert.equal(vector.ports[0].protocol, 'udp');
assert.equal(vector.logging.driver, 'json-file');
assert.equal(vector.environment.TINYCLOUD_LOGSHIP_PROFILE, '${TINYCLOUD_LOGSHIP_PROFILE:-errors_slow}');
const embedded = vector.environment.VECTOR_CONFIG_JSON.replaceAll('$${TINYCLOUD_LOGSHIP_PROFILE}', '${TINYCLOUD_LOGSHIP_PROFILE}');
assert.ok(isDeepStrictEqual(JSON.parse(embedded), buildConfig({ runtimeProfile: true })), 'embedded Vector config differs from schema/compiler sources');
const schema = JSON.parse(bytes).services['tinycloud-node'];
assert.equal(schema.events.includes('node_fatal_panic'), false);
const diagnostics = JSON.parse(readFileSync(resolve(root, 'log-shipper/diagnostics.json'), 'utf8'));
for (const code of [...Object.values(diagnostics.exact), ...Object.values(diagnostics.prefix), diagnostics.fallback]) assert.ok(schema.fields.event_code.values.includes(code));
console.log('TC-959 schema pin, compose isolation, image pins and embedded Vector parity passed');
